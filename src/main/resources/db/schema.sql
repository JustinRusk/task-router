-- Schema for the routing engine. Safe to re-run.
-- Not run automatically: Spring only auto-runs schema.sql at the resources root, and only for embedded databases.

CREATE TABLE IF NOT EXISTS interactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caller_number VARCHAR(32) NOT NULL,
    dialed_number VARCHAR(32) NOT NULL,
    status        VARCHAR(16) NOT NULL
        CHECK (status IN ('RECEIVED', 'ROUTED', 'COMPLETED', 'ABANDONED')),
    created_at    TIMESTAMPTZ NOT NULL
);

-- Destinations that interactions are routed to.
CREATE TABLE IF NOT EXISTS queues (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL UNIQUE
);

-- Rules are evaluated in ascending priority; the first match wins. NULL conditions match anything.
CREATE TABLE IF NOT EXISTS routing_rules (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    priority        INT          NOT NULL UNIQUE,
    dialed_number   VARCHAR(32),
    caller_prefix   VARCHAR(32),
    target_queue_id BIGINT       NOT NULL REFERENCES queues (id),
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Routing decision recorded on each interaction.
ALTER TABLE interactions ADD COLUMN IF NOT EXISTS routed_queue_id BIGINT REFERENCES queues (id);
ALTER TABLE interactions ADD COLUMN IF NOT EXISTS matched_rule_id BIGINT REFERENCES routing_rules (id);
ALTER TABLE interactions ADD COLUMN IF NOT EXISTS routed_at       TIMESTAMPTZ;
